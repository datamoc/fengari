"use strict";

/*
** Bundles src/fengari.js (and sprintf-js) into a single browser script,
** docs/benchmark/fengari.bundle.js, exposed as the global `Fengari`.
** Node-only modules are replaced by empty stubs: the browser code paths are
** guarded by `typeof process === "undefined"` and never reach them.
*/

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const entry = path.join(root, "src", "fengari.js");
const output = path.join(root, "docs", "benchmark", "fengari.bundle.js");
const nodeOnly = new Set(["fs", "os", "path", "tmp", "child_process", "readline-sync"]);

const modules = new Map(); /* absolute filename -> { id, code, deps: { specifier: id } } */

function resolveFile(specifier, from) {
    if (nodeOnly.has(specifier)) return null;
    if (specifier.startsWith(".")) return require.resolve(path.resolve(path.dirname(from), specifier));
    return require.resolve(specifier, { paths: [from] });
}

function add(filename) {
    if (modules.has(filename)) return modules.get(filename).id;
    const entryModule = { id: modules.size, code: fs.readFileSync(filename, "utf8"), deps: {} };
    modules.set(filename, entryModule);
    const live = entryModule.code.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, ""); /* ignore commented-out requires */
    for (const [, , specifier] of live.matchAll(/\brequire\((['"])([^'"]+)\1\)/g)) {
        if (specifier in entryModule.deps) continue;
        const resolved = resolveFile(specifier, filename);
        entryModule.deps[specifier] = resolved === null ? -1 : add(resolved);
    }
    return entryModule.id;
}

const entryId = add(entry);
const factories = [...modules.values()].map(({ id, code, deps }) =>
    `${id}: [function(require, module, exports) {\n${code}\n}, ${JSON.stringify(deps)}]`);

const bundle = `/* @datamoc/fengari browser bundle - generated by tools/build-benchmark.js, do not edit */
(function(global) {
"use strict";
var factories = {
${factories.join(",\n")}
};
var cache = {};
function load(id) {
    if (cache[id]) return cache[id].exports;
    var module = cache[id] = { exports: {} };
    var factory = factories[id];
    factory[0](function(specifier) {
        var dep = factory[1][specifier];
        if (dep === undefined) throw new Error("Cannot find module '" + specifier + "'");
        if (dep === -1) throw new Error("Module '" + specifier + "' is not available in the browser");
        return load(dep);
    }, module, module.exports);
    return module.exports;
}
global.Fengari = load(${entryId});
})(typeof window !== "undefined" ? window : globalThis);
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, bundle);
console.log(`${path.relative(root, output)}: ${modules.size} modules, ${(bundle.length / 1024).toFixed(0)} KiB`);
